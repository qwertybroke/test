def smooth(t):
    return t * t * (3 - 2 * t)


def bow_t(y):
    return min(1.0, max(0.0, (-30.0 - y) / (-30.0 - Y_NOSE)))


def ramp(y, a, b, c, d):
    if y <= a or y >= d:
        return 0.0
    if y < b:
        return (y - a) / (b - a)
    if y > c:
        return (d - y) / (d - c)
    return 1.0


