def params(y):
    p = dict(MID)
    if y < BOW_KEYS[-1][0]:
        ks = BOW_KEYS
        k = 1
        while k < len(ks) - 1 and ks[k][0] < y:
            k += 1
        a, b = ks[k - 1], ks[k]
        t = min(1.0, max(0.0, (y - a[0]) / (b[0] - a[0])))
        for i, key in enumerate(("W", "zT", "wT", "zSh", "zL", "zK", "wK")):
            p[key] = a[i + 1] + (b[i + 1] - a[i + 1]) * t
    # корма: лёгкое сужение киля и верхней палубы
    s = min(1.0, max(0.0, (y - 38.0) / (Y_STERN - 38.0)))
    p["zK"] += 1.0 * s ** 2
    p["wK"] -= 0.8 * s ** 2
    p["wT"] -= 0.5 * s ** 2
    p["sh"] = SPINE_H * ramp(y, *SPINE_Y)
    p["belt"] = max((BELT_D * ramp(y, a, a + 0.35, b - 0.35, b) for a, b in BELT), default=0.0)
    p["beltA"] = max((0.3 * ramp(y, a, a + 0.3, b - 0.3, b) for a, b in BELT_A), default=0.0)
    return p


def wall_z(p, z):
    """Перенос отметки z с борта миделя (zL..zSh) на борт текущего шпангоута."""
    zl0, zs0 = MID["zL"], MID["zSh"]
    return p["zL"] + (z - zl0) / (zs0 - zl0) * (p["zSh"] - p["zL"])


